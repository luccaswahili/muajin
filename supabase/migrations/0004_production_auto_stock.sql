-- p_damaged: [{"material_id": "...", "qty": 3}, ...]
create or replace function public.record_production(
  p_product_id uuid, p_drums numeric, p_cartons int, p_loose_bottles int default 0,
  p_date date default current_date, p_notes text default '',
  p_damaged jsonb default '[]'::jsonb,
  p_labour_cost numeric default 0, p_labour_paid_from text default 'cash'
) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  prod products%rowtype;
  v_id uuid;
  v_no int;
  v_bottles int;
  v_cartons int := coalesce(p_cartons, 0);
  v_drums numeric := coalesce(p_drums, 0);
  v_qty numeric;
  m record;
  d jsonb;
  v_cat uuid;
begin
  perform require_perm('production');
  select * into prod from products where id = p_product_id;
  if not found then raise exception 'Product not found'; end if;
  if v_cartons < 0 or coalesce(p_loose_bottles, 0) < 0 or v_drums < 0 then raise exception 'Numbers cannot be negative'; end if;
  if v_cartons = 0 and coalesce(p_loose_bottles, 0) = 0 then raise exception 'Enter how many cartons were produced'; end if;
  v_bottles := v_cartons * prod.bottles_per_carton + coalesce(p_loose_bottles, 0);

  insert into productions (date, product_id, drums_used, ethanol_litres, cartons_produced, loose_bottles, notes)
  values (p_date, p_product_id, v_drums,
          v_drums * coalesce((select (value #>> '{}')::numeric from settings where key = 'drum_litres'), 250),
          v_cartons, coalesce(p_loose_bottles, 0), coalesce(p_notes, ''))
  returning id, batch_no into v_id, v_no;

  insert into product_movements (date, product_id, bottles, reason, production_id, notes)
  values (p_date, p_product_id, v_bottles, 'production', v_id, format('Produced in batch #%s', v_no));

  -- Materials used, by each material's usage rule
  for m in select * from materials
           where is_active and usage <> 'none' and usage_qty > 0 and (product_id is null or product_id = p_product_id)
  loop
    v_qty := case m.usage
      when 'per_bottle' then v_bottles * m.usage_qty
      when 'per_carton' then v_cartons * m.usage_qty
      when 'per_drum' then v_drums * m.usage_qty
    end;
    if v_qty > 0 then
      insert into material_movements (date, material_id, qty, unit_cost, reason, production_id, notes)
      values (p_date, m.id, -round(v_qty, 2), m.unit_cost, 'production', v_id,
              format('Auto-deducted by production batch #%s', v_no));
    end if;
  end loop;

  -- Items damaged during the batch
  for d in select * from jsonb_array_elements(coalesce(p_damaged, '[]'::jsonb)) loop
    v_qty := (d ->> 'qty')::numeric;
    if v_qty is not null and v_qty > 0 then
      insert into material_movements (date, material_id, qty, unit_cost, reason, production_id, notes)
      select p_date, id, -v_qty, unit_cost, 'damage', v_id,
             format('Damaged during production batch #%s', v_no) || coalesce(nullif(' · ' || (d ->> 'note'), ' · '), '')
      from materials where id = (d ->> 'material_id')::uuid;
    end if;
  end loop;

  if coalesce(p_labour_cost, 0) > 0 then
    select id into v_cat from expense_categories where name = 'Temporary workers';
    if v_cat is null then
      insert into expense_categories (name) values ('Temporary workers') returning id into v_cat;
    end if;
    insert into expenses (date, category_id, amount, description, paid_from, production_id)
    values (p_date, v_cat, p_labour_cost, format('Workers for batch #%s', v_no), coalesce(p_labour_paid_from, 'cash'), v_id);
  end if;
  return v_id;
end $$;

revoke execute on function public.record_production(uuid, numeric, int, int, date, text, jsonb, numeric, text) from public, anon;
grant execute on function public.record_production(uuid, numeric, int, int, date, text, jsonb, numeric, text) to authenticated;

-- Recreate so the view picks up batch_no
drop view public.v_production_costs;
create view public.v_production_costs with (security_invoker = true) as
select pd.*, p.name as product_name, p.bottles_per_carton, p.price_carton, pr.full_name as created_by_name,
  coalesce((select sum(-m.qty * m.unit_cost) from material_movements m where m.production_id = pd.id), 0) as material_cost,
  coalesce((select sum(e.amount) from expenses e where e.production_id = pd.id), 0) as other_cost,
  coalesce((select sum(-m.qty * m.unit_cost) from material_movements m where m.production_id = pd.id), 0)
    + coalesce((select sum(e.amount) from expenses e where e.production_id = pd.id), 0) as total_cost,
  case when pd.cartons_produced + pd.loose_bottles::numeric / p.bottles_per_carton > 0 then
    (coalesce((select sum(-m.qty * m.unit_cost) from material_movements m where m.production_id = pd.id), 0)
      + coalesce((select sum(e.amount) from expenses e where e.production_id = pd.id), 0))
    / (pd.cartons_produced + pd.loose_bottles::numeric / p.bottles_per_carton)
  end as cost_per_carton,
  case when pd.drums_used > 0 then (pd.cartons_produced + pd.loose_bottles::numeric / p.bottles_per_carton) / pd.drums_used end as cartons_per_drum
from productions pd
join products p on p.id = pd.product_id
left join profiles pr on pr.id = pd.created_by;
