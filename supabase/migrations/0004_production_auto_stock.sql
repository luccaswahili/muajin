-- Production batches: numbered, automatic material deduction by clear usage rules, damaged items.

alter table public.productions add column batch_no int generated by default as identity;
alter table public.productions add constraint productions_batch_no_key unique (batch_no);

-- One clear rule per material: how much is used per bottle, per carton or per ethanol drum.
alter table public.materials
  add column usage text not null default 'none' check (usage in ('none', 'per_bottle', 'per_carton', 'per_drum')),
  add column usage_qty numeric(14,4) not null default 0 check (usage_qty >= 0),
  add column product_id uuid references public.products(id) on delete set null;

update public.materials set usage = 'per_drum', usage_qty = case when lower(unit) like 'drum%' then 1 else 250 end where name ilike 'ethanol%';
update public.materials set usage = 'per_drum', usage_qty = 0.1 where name ilike '%flavo%';
update public.materials set product_id = (select id from public.products where name ilike '%dry%' limit 1) where name ilike '%dry%flavo%';
update public.materials set product_id = (select id from public.products where name ilike '%coffee%' limit 1) where name ilike '%coffee%flavo%';
update public.materials set usage = 'per_bottle', usage_qty = 1
  where name ilike 'bottle%' or name ilike '%cap%' or name ilike '%label%' or name ilike '%stamp%';
update public.materials set usage = 'per_carton', usage_qty = 1 where name ilike '%box%' or name ilike 'carton%';

drop view public.v_material_stock;
alter table public.materials drop column per_bottle, drop column per_carton;

create view public.v_material_stock with (security_invoker = true) as
select mt.id as material_id, mt.name, mt.unit, mt.unit_cost, mt.low_stock_level, mt.is_active, mt.sort,
  mt.usage, mt.usage_qty, mt.product_id,
  coalesce(sum(m.qty), 0) as qty
from materials mt left join material_movements m on m.material_id = mt.id
group by mt.id;

update public.settings set label = 'Not used anymore' where key in ('flavor_pct', 'ethanol_material_id');
update public.settings set label = 'Ethanol % in the mix (for the mix guide only)' where key = 'ethanol_pct';

